def process_and_rename_replicates(csv_path, strain, n_replicates, output_folder):
    """
    Reads the generated CSV, removes specific columns and renames 
    replicate columns as R1, R2, R3, etc.
    
    Columns removed: Well, Resources, OD600 24h mean, OD600 24h std
    Columns renamed: OD600 24h repN → RN
    
    Args:
        csv_path: path to CSV generated by write_clean_data_to_csv
        strain: strain name
        n_replicates: number of replicates for that strain
        output_folder: folder where to save the processed CSV
    """
    try:
        # Read the CSV
        df = pd.read_csv(csv_path)
        
        print(f"  ℹ Original CSV dimensions: {df.shape[0]} rows × {df.shape[1]} columns")
        print(f"  ℹ Original columns: {list(df.columns)}")
        
        # Columns to drop
        cols_to_drop = ['Well', 'Resources', 'OD600 24h mean', 'OD600 24h std']
        cols_to_drop = [col for col in cols_to_drop if col in df.columns]
        
        if cols_to_drop:
            df = df.drop(columns=cols_to_drop)
            print(f"  ✓ Columns removed: {cols_to_drop}")
        
        # Rename replicate columns
        rename_dict = {}
        
        for col in df.columns:
            # Search for pattern "repN" where N is a number
            match = re.search(r'rep(\d+)', col, re.IGNORECASE)
            if match:
                rep_number = match.group(1)
                rename_dict[col] = f'R{rep_number}'
        
        if rename_dict:
            df = df.rename(columns=rename_dict)
            print(f"  ✓ Replicate columns renamed:")
            for old, new in rename_dict.items():
                print(f"      {old} → {new}")
        
        print(f"  ✓ Processed CSV dimensions: {df.shape[0]} rows × {df.shape[1]} columns")
        print(f"  ℹ Final columns: {list(df.columns)}")
        
        # Create output folder if it doesn't exist
        if not os.path.exists(output_folder):
            os.makedirs(output_folder)
        
        # Save the processed CSV
        output_filename = f'{strain}_L8_resources.csv'
        output_path = os.path.join(output_folder, output_filename)
        df.to_csv(output_path, index=False)
        
        print(f"  ✓ Processed CSV saved: {output_filename}")
        
        return True
        
    except Exception as e:
        print(f"  ✗ ERROR processing CSV for {strain}: {e}")
        import traceback
        traceback.print_exc()
        return False


