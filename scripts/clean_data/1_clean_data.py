def get_blank_from_plate1(filepath):
  
    wb = openpyxl.load_workbook(filepath, data_only=True)
    ws = wb.active

    for row in ws.iter_rows():
        for cell in row:
            if cell.value == 'Abs':
                data_start_row = cell.row + 1
                data_start_col = cell.column + 1
                blank = ws.cell(row=data_start_row, column=data_start_col).value
                if isinstance(blank, str):
                    blank = float(blank.replace(',', '.'))
                return float(blank)

    raise ValueError(f"Not found: {filepath}")


